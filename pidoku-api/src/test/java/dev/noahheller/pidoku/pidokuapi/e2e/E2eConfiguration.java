package dev.noahheller.pidoku.pidokuapi.e2e;

import dev.noahheller.pidoku.pidokuapi.generation.DailyPuzzleScheduler;
import dev.noahheller.pidoku.pidokuapi.generation.PuzzleGenerator;
import dev.noahheller.pidoku.pidokuapi.puzzle.Difficulty;
import dev.noahheller.pidoku.pidokuapi.puzzle.PuzzleService;
import dev.noahheller.pidoku.pidokuapi.puzzle.PuzzleSource;
import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.SmartInitializingSingleton;
import org.springframework.boot.test.context.TestConfiguration;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Profile;
import org.springframework.security.oauth2.jwt.BadJwtException;
import org.springframework.security.oauth2.jwt.Jwt;
import org.springframework.security.oauth2.jwt.JwtDecoder;

import java.time.Instant;
import java.time.temporal.ChronoUnit;

/**
 * What the Playwright tests need from the API, only with the {@code e2e} profile and only on the
 * test classpath (see {@link E2eApiApplication}).
 *
 * <ul>
 *     <li>Test tokens: the frontend built for e2e ({@code VITE_E2E_AUTH=1}) signs every browser
 *     in as {@code e2e.<uid>} (a bearer token may only hold letters, digits and -._~+/) instead of loading Firebase, and this decoder turns that into a
 *     verified token for the uid. The real decoder (Firebase's keys) backs off when this bean
 *     exists.</li>
 *     <li>Today's dailies, generated by the real engine on startup, so there's something to
 *     play.</li>
 *     <li>A few easy puzzles in the random pool, for tests of puzzles that aren't dailies (challenge
 *     links). Easy only, since harder ones take longer to generate.</li>
 * </ul>
 */
@Slf4j
@TestConfiguration(proxyBeanMethods = false)
@Profile(E2eConfiguration.PROFILE)
public class E2eConfiguration {

    public static final String PROFILE = "e2e";
    static final String TOKEN_PREFIX = "e2e.";

    @Bean
    JwtDecoder e2eJwtDecoder() {
        return token -> {
            if (token == null || !token.startsWith(TOKEN_PREFIX) || token.length() == TOKEN_PREFIX.length()) {
                throw new BadJwtException("Not an e2e test token");
            }
            Instant now = Instant.now();
            return Jwt.withTokenValue(token)
                    .header("alg", "none")
                    .subject(token.substring(TOKEN_PREFIX.length()))
                    .issuedAt(now)
                    .expiresAt(now.plus(1, ChronoUnit.HOURS))
                    .build();
        };
    }

    /** How many easy puzzles the random pool starts with. */
    static final int POOL_PUZZLES = 8;

    /** Runs once every bean is ready, before the web server starts (an ApplicationRunner would be after). */
    @Bean
    SmartInitializingSingleton e2eDailies(DailyPuzzleScheduler scheduler) {
        return () -> log.info("e2e: generated {} daily puzzles", scheduler.scheduleUpcoming());
    }

    @Bean
    SmartInitializingSingleton e2ePool(PuzzleGenerator generator, PuzzleService puzzleService) {
        return () -> {
            int stored = 0;
            for (long seed = 1; stored < POOL_PUZZLES && seed <= POOL_PUZZLES * 3L; seed++) {
                var puzzle = generator.generate(Difficulty.EASY, seed);
                if (puzzle.isPresent()) {
                    puzzleService.store(puzzle.get(), PuzzleSource.POOL);
                    stored++;
                }
            }
            log.info("e2e: stored {} easy pool puzzles", stored);
        };
    }
}
